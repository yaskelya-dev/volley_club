#!/bin/bash
set -e # Остановить скрипт при ошибке любой из команд

echo "ПОДТЯГИВАЕМ ИЗМЕНЕНИЯ С ГИТА"
git pull

echo "ПЕРЕСОБИРАЕМ ДОКЕР"
# Флаг --build заставит Docker пересобрать образ с новыми изменениями,
# а -d запустит контейнеры в фоновом режиме без простоя (zero-downtime reload)
docker compose up -d --build

echo "УДАЛЯЕМ СТАРЫЕ ОБРАЗЫ"
# Удаляет старые неиспользуемые слои и images, чтобы не забивать диск
docker image prune -f

echo "ВСЁ ПРОШЛО УСПЕШНО"
